import { csvLines, RELEASE, reportRows } from './operations.js';
// Slice 6k: reconciled operational export (BR-REP-05). The CSV names its definition, export identifier,
// status, exporting member, window and teams; carries control totals that tie each displayed measure to the
// sum of its detail rows; and ends with a manifest of the row count and SHA-256 of every line above it.
// A receiver checks it with: head -n -2 saha-report.csv | wc -l ; head -n -2 saha-report.csv | sha256sum
export const REPORT_DEFINITION = { id: 'saha-operational-report', version: '1.2.0' };
export const EXPORT_STATUS = 'Draft export; not an official or reviewed submission';
const sum = (xs) => xs.some(x => x === null) ? null : xs.reduce((n, x) => n + (x ?? 0), 0);
export function controlTotals(r) {
    return [
        { measure: 'Visits confirmed in window', displayed: r.visitsConfirmed, fromRows: sum(r.daily.map(d => d.confirmed)), rows: 'Daily confirmations' },
        { measure: 'Open follow-ups', displayed: r.backlog.openFollowUps, fromRows: sum(r.programmes.map(p => p.openTasks)), rows: 'Programme open tasks' },
        { measure: 'Overdue follow-ups', displayed: r.backlog.overdueFollowUps, fromRows: sum(r.programmes.map(p => p.overdueTasks)), rows: 'Programme overdue tasks' },
        { measure: 'Unresolved programme receipts', displayed: r.backlog.unresolvedSubmissions, fromRows: sum(r.destinations.map(d => d.pending)), rows: 'Destination pending now' },
    ].map(t => ({ ...t, fromRows: t.displayed === null ? null : t.fromRows, reconciled: t.displayed === null || t.displayed === t.fromRows }));
}
async function sha256(text) { return [...new Uint8Array(await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text)))].map(b => b.toString(16).padStart(2, '0')).join(''); }
export async function exportCsv(r, meta) {
    const totals = controlTotals(r);
    const rows = [['Saha scoped operational report', RELEASE], ['Report definition', REPORT_DEFINITION.id, REPORT_DEFINITION.version], ['Export identifier', meta.exportId], ['Status', EXPORT_STATUS],
        ['Generated by', meta.generatedBy, meta.role], ['Reporting window days', meta.days], ['Teams in scope', meta.teams.length ? meta.teams.join('; ') : 'None'],
        ...('privacy' in r && r.privacy ? [['Privacy', r.privacy.withheld ? 'Withheld' : 'Protected', r.privacy.reason], ['Active-worker disclosure', r.privacy.activeWorkers]] : []),
        ...reportRows(r).slice(1).map(row => row.map(v => v === null ? 'Withheld' : v)),
        ['Control total', 'Displayed measure', 'Sum of detail rows', 'Detail rows', 'Reconciled'], ...totals.map(t => [t.measure, t.displayed ?? 'Withheld', t.fromRows ?? 'Withheld', t.rows, t.reconciled ? 'yes' : 'no'])];
    // One physical line per row, so line counts and the manifest agree: line breaks inside cells become spaces.
    const flat = rows.map(row => row.map(v => typeof v === 'string' ? v.replace(/[\r\n]+/g, ' ') : v));
    const body = csvLines(flat), hash = await sha256(body), lines = flat.length;
    return { csv: body + csvLines([['Manifest', 'Data rows', lines], ['Manifest', 'Content SHA-256', hash]]), sha256: hash, rows: lines, reconciled: totals.every(t => t.reconciled) };
}
// What a receiver (or a test) does with a received file: recount, rehash and read the control totals.
export async function verifyExportCsv(csv) {
    const lines = csv.split('\r\n');
    if (lines.at(-1) === '')
        lines.pop();
    const problems = [];
    const trailer = lines.slice(-2), body = lines.slice(0, -2);
    const rowCount = /^"Manifest","Data rows","(\d+)"$/.exec(trailer[0] ?? ''), hash = /^"Manifest","Content SHA-256","([0-9a-f]{64})"$/.exec(trailer[1] ?? '');
    if (!rowCount || !hash)
        return { ok: false, problems: ['Manifest lines missing or malformed'] };
    if (Number(rowCount[1]) !== body.length)
        problems.push(`Row count ${body.length} differs from manifest ${rowCount[1]}`);
    const actual = await sha256(body.map(l => l + '\r\n').join(''));
    if (actual !== hash[1])
        problems.push('Content SHA-256 differs from manifest');
    const start = body.findIndex(l => l.startsWith('"Control total",'));
    if (start < 0)
        problems.push('Control totals missing');
    else
        for (const l of body.slice(start + 1))
            if (!l.endsWith(',"yes"'))
                problems.push('Control total not reconciled: ' + l);
    return { ok: !problems.length, problems, rows: body.length, sha256: actual };
}
