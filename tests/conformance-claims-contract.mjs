import assert from 'node:assert/strict';
import ts from 'typescript';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {pathToFileURL} from 'node:url';

const root=process.cwd(),tmp=fs.mkdtempSync(path.join(os.tmpdir(),'saha-conformance-'));
const source=fs.readFileSync(path.join(root,'lib/saha/conformance.ts'),'utf8');
fs.writeFileSync(path.join(tmp,'conformance.mjs'),ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
const {conformanceAssessment}=await import(pathToFileURL(path.join(tmp,'conformance.mjs')));
const connector={mode:'http',status:'active',conformance:{syntactic:{passedAt:'2026-01-01',evidence:'schema-1'},sandbox:{passedAt:'2026-01-02',evidence:'sandbox-1'}}};
const before=JSON.stringify(connector);
let r=conformanceAssessment(connector);
assert.equal(r.productionLive,false,'sandbox success must never collapse into a production-live claim');
assert.deepEqual(r.stages.map(s=>s.id),['syntactic','sandbox','security','certification','onboarding','live']);
assert.equal(r.stages.find(s=>s.id==='sandbox').complete,true);
assert.equal(r.stages.find(s=>s.id==='security').complete,false);
assert.ok(r.missing.includes('Production credentials'));
assert.equal(JSON.stringify(connector),before,'assessment is read-only and safe under concurrent refresh');
connector.conformance={...connector.conformance,securityReview:{approvedAt:'2026-01-03',evidence:'security-1'},partnerCertification:{certifiedAt:'2026-01-04',evidence:'cert-1'},productionOnboarding:{completedAt:'2026-01-05',evidence:'onboard-1'},credentials:{binding:'SAHA_EHR_KEY',recordedAt:'2026-01-05'},ownerApproval:{ownerId:'owner-1',approvedAt:'2026-01-05',evidence:'approval-1'},endToEndTransaction:{completedAt:'2026-01-06',receipt:'receipt-1'},supportResponsibility:{owner:'Integration operations',recordedAt:'2026-01-06'},liveAcceptance:{acceptedAt:'2026-01-07',evidence:'acceptance-1'}};
r=conformanceAssessment(connector);
assert.equal(r.productionLive,true);
assert.deepEqual(r.missing,[]);
assert.equal(conformanceAssessment({...connector,status:'suspended'}).productionLive,false,'a suspended connector is not production-live');
assert.equal(conformanceAssessment({...connector,mode:'demo'}).productionLive,false,'a demo connector is not production-live');
connector.conformance.ownerApproval={ownerId:'',approvedAt:'2026-01-05',evidence:'approval-1'};
r=conformanceAssessment(connector);
assert.equal(r.productionLive,false,'missing accountable owner refuses the claim');
assert.ok(r.missing.includes('Owner approval'));
connector.conformance.ownerApproval={ownerId:'owner-1',approvedAt:'2026-01-05',evidence:'   '};
assert.equal(conformanceAssessment(connector).productionLive,false,'blank evidence is refused');
console.log('conformance claims contract: 17 checks passed');
