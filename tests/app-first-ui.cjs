// Rendered component policy and status tests; full browser journey lives in tests/ui/app-first-phone.spec.mjs.
const assert=require('node:assert/strict'),path=require('node:path'),fs=require('node:fs');
const build=require(require.resolve('esbuild',{paths:[require.resolve('vite')]}));
const root=path.resolve(__dirname,'..'),bundle=path.join(root,'.sites-runtime','app-first-ui.cjs');
fs.mkdirSync(path.dirname(bundle),{recursive:true});
build.buildSync({entryPoints:[path.join(root,'app/frontline-navigation.tsx')],bundle:true,platform:'node',format:'cjs',packages:'external',outfile:bundle,tsconfig:path.join(root,'tsconfig.json'),logLevel:'silent'});
const React=require('react'),{renderToStaticMarkup}=require('react-dom/server');
const {FrontlineNavigation,FrontlineSync,FrontlineMore}=require(bundle);
let count=0;const check=f=>{f();count++};
const data=role=>({role,membership:{isOwner:false,displayName:'Synthetic Worker'},user:{displayName:'Synthetic Worker'},organisation:{id:'org_synthetic',name:'Synthetic organisation'},organisations:[{id:'org_synthetic',name:'Synthetic organisation'}],delegatedAuthority:[]});
const nav=(role,extra={})=>renderToStaticMarkup(React.createElement(FrontlineNavigation,{data:role?data(role):null,view:'work',tab:'home',patientOpen:false,busy:false,pilotTask:false,go(){},choose(){},...extra}));
check(()=>assert.match(nav('asha'),/>Home<.*>People<.*>Referrals<.*>Sync<.*>More</));
check(()=>assert.match(nav('asha'),/aria-current="page"/));
check(()=>assert.doesNotMatch(nav('asha',{patientOpen:true}),/aria-current="page"/));
check(()=>assert.doesNotMatch(nav('provider'),/>Today<|>People<|>Referrals<|>Sync</));
check(()=>assert.doesNotMatch(nav('admin'),/>Sync</));
check(()=>assert.match(nav('clinician'),/>Sync</));
check(()=>assert.doesNotMatch(nav(null),/>Today<|>People<|>Referrals<|>Sync</));
check(()=>assert.equal((nav('asha',{busy:true}).match(/disabled=""/g)||[]).length,5));
const sync=online=>renderToStaticMarkup(React.createElement(FrontlineSync,{online,busy:false,openNotebook(){},openSubmissions(){}}));
check(()=>assert.match(sync(true),/encrypted queue is not read by this screen/));
check(()=>assert.match(sync(true),/unconfirmed server draft; it does not send it to a programme/));
check(()=>assert.match(sync(false),/Browser reports offline/));
check(()=>assert.match(sync(true),/Server availability is checked when you load or sync/));
check(()=>assert.doesNotMatch(sync(true),/0 drafts|All synced|Everything synced/));
const more=renderToStaticMarkup(React.createElement(FrontlineMore,{data:data('asha'),pilotTask:false,busy:false,go(){},switchOrg(){},setLanguage(){}}));
check(()=>assert.doesNotMatch(more,/>Clinical governance<|>Operations<|>Connections</));
check(()=>assert.match(more,/Open full web workspace/));
const report={date:'2026-10-05',passed:count,failed:0,scope:'Rendered React component role policy and honest device/server status; browser interaction, Android and physical-device QA not covered.'};
fs.mkdirSync('tests/evidence/app-first-ui',{recursive:true});
fs.writeFileSync('tests/evidence/app-first-ui/component-result.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
