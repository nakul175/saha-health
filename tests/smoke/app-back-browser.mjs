// Real Chromium and isolated Worker/D1: browser Back/Forward, not a simulated native bridge.
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { startWorker, identity, client } from '../lib/worker.mjs';
const { chromium } = await import(process.env.SAHA_BROWSER_PACKAGE ?? '@playwright/test');
const evidence='tests/evidence/app-back-navigation';
const checks=[];let worker,browser;
const check=(name,value)=>{assert.ok(value,name);checks.push(name);};
mkdirSync(evidence,{recursive:true});
try{
 worker=await startWorker({port:process.env.SAHA_APP_BACK_PORT??'8851',name:'saha-app-back'});
 const api=client(worker.base),run=crypto.randomUUID().slice(0,8),owner=identity('owner',run),asha=identity('asha',run);
 const wo=await api.get(owner,'/api/workspace'),wa=await api.get(asha,'/api/workspace'),org=wo.json.organisation.id,p=wo.json.people.find(p=>p.name==='Meena Devi');
 const invite=await api.command(owner,{type:'createInvite',accountCode:wa.json.user.accountCode,label:'Synthetic ASHA',role:'asha',teamIds:['default']},org);
 assert.equal((await api.command(asha,{type:'joinOrganisation',token:invite.json.result.token})).status,200);
 assert.equal((await api.command(owner,{type:'assignPatient',personId:p.id,version:p.version,teamId:'default',assignedTo:wa.json.user.userId,reason:'Synthetic browser Back check'},org)).status,200);
 browser=await chromium.launch({headless:true,...(process.env.SAHA_CHROMIUM?{executablePath:process.env.SAHA_CHROMIUM}:{})});
 const context=await browser.newContext({viewport:{width:390,height:844},extraHTTPHeaders:asha.headers});
 const page=await context.newPage();page.setDefaultTimeout(20000);
 await page.goto(worker.base+'/');await page.getByRole('heading',{name:'Today’s work',exact:true}).waitFor();
 await page.goto(worker.base+'/app');
 const nav=page.getByRole('navigation',{name:'App navigation'});
 await nav.getByRole('button',{name:'Today',exact:true}).waitFor();
 await page.waitForFunction(()=>history.state?.sahaApp?.index===0);
 await nav.getByRole('button',{name:'Sync',exact:true}).click();await page.getByRole('heading',{name:'Your sync centre'}).waitFor();
 await page.goBack();await page.getByRole('heading',{name:'Today',exact:true}).waitFor();
 check('clean Back returns to Today without leaving /app',new URL(page.url()).pathname==='/app');
 await page.goForward();await page.getByRole('heading',{name:'Your sync centre'}).waitFor();checks.push('Forward restores Sync');
 await page.goBack();await page.getByRole('heading',{name:'Today',exact:true}).waitFor();
 await page.getByRole('button',{name:/Meena Devi/}).first().click();await page.getByRole('heading',{name:'Meena Devi',exact:true}).waitFor();
 await page.getByRole('button',{name:'Start visit',exact:true}).click();
 const weight=page.getByRole('textbox',{name:'Weight · kg',exact:true});await weight.fill('57.5');
 await page.getByText('Unsaved changes',{exact:true}).waitFor();
 const position=await page.evaluate(()=>history.state.sahaApp.index);
 await page.goBack();await page.getByRole('alertdialog').waitFor();
 check('dirty Back restores current history position before asking',await page.evaluate(()=>history.state.sahaApp.index)===position);
 await page.getByRole('button',{name:'Keep editing',exact:true}).click();
 check('cancelled Back retains unsaved weight',await weight.inputValue()==='57.5');
 await page.goBack();await page.getByRole('alertdialog').waitFor();
 await page.getByRole('button',{name:'Discard edits',exact:true}).click();
 await page.getByRole('heading',{name:'Today',exact:true}).waitFor();checks.push('discarded Back returns to Today');
 let current=await api.get(asha,'/api/workspace',org),visit=current.json.visits.find(v=>v.personId===p.id&&v.state==='draft');
 check('discarded local weight was never written to server',visit&&visit.facts.weight!=='57.5');
 await page.goForward();await page.getByRole('heading',{name:'Meena Devi',exact:true}).waitFor();
 check('Forward restores existing visit with server facts',await weight.inputValue()===visit.facts.weight);
 await weight.fill('58.2');await page.getByRole('button',{name:'Save draft',exact:true}).click();
 await page.getByText('Draft saved in the workspace.',{exact:true}).waitFor();
 await page.goBack();await page.getByRole('heading',{name:'Today',exact:true}).waitFor();
 await page.goForward();await page.getByRole('heading',{name:'Meena Devi',exact:true}).waitFor();
 check('saved draft survives clean Back and Forward',await weight.inputValue()==='58.2');
 current=await api.get(asha,'/api/workspace',org);visit=current.json.visits.find(v=>v.id===visit.id);
 check('server readback remains the same unconfirmed draft',visit.state==='draft'&&visit.facts.weight==='58.2');
 const state=JSON.stringify(await page.evaluate(()=>history.state));
 check('history stores no patient identifiers, facts, account or token',![p.id,visit.id,'Meena','58.2',asha.id,'Idempotency-Key'].some(value=>state.includes(value)));
 await page.goBack();await page.getByRole('heading',{name:'Today',exact:true}).waitFor();
 await page.goBack();await page.getByRole('heading',{name:'Today’s work',exact:true}).waitFor();
 check('root Back exits to preceding full workspace without a sentinel trap',new URL(page.url()).pathname==='/');
 writeFileSync(evidence+'/browser-result.json',JSON.stringify({passed:checks.length,checks,completedAt:new Date().toISOString(),limits:'Real cached Chromium/local synthetic D1. TWA uses this browser history; no physical Android system-Back test, hosted Access or clinical acceptance.'},null,2)+'\n');
 console.log(JSON.stringify({passed:checks.length}));
}finally{await browser?.close();await worker?.stop();}
