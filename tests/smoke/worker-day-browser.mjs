// Synthetic local Worker/D1 with the existing trusted-dispatcher harness; never run against a live host.
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { startWorker, identity, client } from '../lib/worker.mjs';
const { chromium } = await import(process.env.SAHA_BROWSER_PACKAGE ?? '@playwright/test');
const folder = 'tests/reports/worker-day';
mkdirSync(folder, { recursive: true });
let worker, browser, page, passed = 0;
const check = (value, message) => { assert.ok(value, message); passed++; };
try {
  worker = await startWorker({ port: process.env.SAHA_WORKER_DAY_PORT ?? '9157', name: 'saha-worker-day' });
  const api = client(worker.base), run = crypto.randomUUID().slice(0, 8);
  const owner = identity('owner', run, 'Synthetic Owner'), asha = identity('asha', run, 'Synthetic ASHA');
  const wo = await api.get(owner, '/api/workspace'), wa = await api.get(asha, '/api/workspace');
  assert.equal(wo.status, 200); assert.equal(wa.status, 200);
  const org = wo.json.organisation.id, p = wo.json.people.find(person => person.name === 'Meena Devi');
  assert.ok(p);
  const invite = await api.command(owner, { type: 'createInvite', accountCode: wa.json.user.accountCode, label: 'Synthetic ASHA', role: 'asha', teamIds: ['default'] }, org);
  assert.equal(invite.status, 200);
  assert.equal((await api.command(asha, { type: 'joinOrganisation', token: invite.json.result.token })).status, 200);
  assert.equal((await api.command(owner, { type: 'assignPatient', personId: p.id, version: p.version, teamId: 'default', assignedTo: wa.json.user.userId, reason: 'Synthetic worker-day check' }, org)).status, 200);
  browser = await chromium.launch({ headless: true, ...(process.env.SAHA_CHROMIUM ? { executablePath: process.env.SAHA_CHROMIUM } : {}) });
  const context = await browser.newContext({ viewport: { width: 360, height: 640 }, extraHTTPHeaders: asha.headers });
  page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  page.setDefaultTimeout(25000);
  await page.goto(worker.base + '/app');
  await page.getByRole('heading', { name: 'What would you like to do?', exact: true }).waitFor();
  check(await page.locator('.guided-choices button').count() === 3, 'Default home is unchanged');
  await page.goto(worker.base + '/app?experience=worker-day');
  await page.locator('#worker-today-title').waitFor();
  const nav = page.getByRole('navigation', { name: 'App navigation' });
  check(await nav.getByRole('button').count() === 3, 'Three stable destinations');
  check(await page.locator('.worker-day-next h2').textContent() === 'Meena Devi', 'Next record comes from assigned source');
  check(await page.locator('.worker-day').getByText('NEXT IN YOUR LIST').count() === 1, 'No fabricated clinical priority');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '360px has no horizontal overflow');
  const primary = page.getByRole('button', { name: 'Open record', exact: true });
  const geometry = await primary.boundingBox();
  check(geometry && geometry.height >= 44, 'Primary touch target');
  await primary.scrollIntoViewIfNeeded();
  await page.screenshot({ path: folder + '/today-360.png', fullPage: true });
  await primary.click();
  await page.getByRole('heading', { name: 'Meena Devi', exact: true }).waitFor();
  await page.locator('#worker-today-title').waitFor({ state: 'hidden' });
  check(!await page.locator('#worker-today-title').isVisible(), 'Person context replaces Today');
  await page.getByRole('button', { name: 'Start visit', exact: true }).click();
  const picker = page.getByRole('combobox', { name: 'Go to observation or save', exact: true });
  await picker.waitFor();
  const choose = async id => {
    await picker.selectOption(id);
    await page.locator('.capture-stage[data-capture-step="' + id + '"]:visible').first().waitFor();
  };
  await choose('fact:weight');
  const weight = page.getByRole('textbox', { name: 'Weight · kg', exact: true });
  await weight.fill('57.5');
  await nav.getByRole('button', { name: 'My Space', exact: true }).click();
  await page.getByRole('alertdialog').waitFor();
  await page.getByRole('button', { name: 'Keep editing', exact: true }).click();
  check(await weight.inputValue() === '57.5', 'Existing dirty-navigation protection retains data');
  await choose('facts-save');
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await page.getByText('Draft saved in the workspace.', { exact: true }).waitFor();
  const saved = (await api.get(asha, '/api/workspace', org)).json;
  const v = saved.visits.find(visit => visit.personId === p.id);
  check(v && v.state === 'draft' && v.facts.weight === '57.5', 'Built backend read-back matches saved draft');
  await page.getByRole('tab', { name: /Review & act/ }).click();
  check(await page.getByRole('button', { name: 'Confirm visit', exact: true }).isDisabled(), 'Existing person check remains required; no extra approval');
  await nav.getByRole('button', { name: 'Today', exact: true }).click();
  await page.locator('#worker-today-title').waitFor();
  await page.getByRole('button', { name: 'Open record', exact: true }).click();
  await page.getByRole('heading', { name: 'Meena Devi', exact: true }).waitFor();
  const after = (await api.get(asha, '/api/workspace', org)).json;
  check(after.visits.length === saved.visits.length, 'Returning to the record does not create another visit');
  check(after.visits.find(visit => visit.id === v.id).facts.weight === '57.5', 'Existing draft survives navigation');
  await nav.getByRole('button', { name: 'My Space', exact: true }).click();
  await page.locator('#worker-space-title').waitFor();
  check(await page.getByRole('button', { name: /Saved work/ }).isVisible(), 'Saved work discoverable in My Space');
  check(!await page.getByRole('button', { name: 'Connections', exact: true }).count(), 'No provider administration on new surface');
  await nav.getByRole('button', { name: 'People', exact: true }).click();
  await page.getByRole('heading', { name: 'People in your care', exact: true }).waitFor();
  check(await nav.getByRole('button', { name: 'People', exact: true }).getAttribute('aria-current') === 'page', 'People uses existing scoped view');
  await page.route('**/api/workspace', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Synthetic source unavailable' }) }));
  await page.reload();
  await page.getByRole('alert').filter({ hasText: 'Synthetic source unavailable' }).waitFor();
  check(!await page.locator('.worker-day-next').count(), 'Failed source is not rendered as an empty/successful caseload');
  await page.unroute('**/api/workspace');
  const other = await browser.newContext({ viewport: { width: 390, height: 844 }, extraHTTPHeaders: owner.headers });
  const otherPage = await other.newPage();
  await otherPage.goto(worker.base + '/app?experience=worker-day');
  await otherPage.getByRole('heading', { name: 'Today', exact: true }).waitFor();
  check(!await otherPage.locator('#worker-today-title').count(), 'Non-ASHA keeps the existing default');
  await other.close();
  check(errors.length === 0, 'No application errors during the new journey');
  const result = { passed, failed: 0, scope: 'Real browser/local synthetic Worker and D1; saves an unconfirmed draft. No offline, physical-device, clinical, government or production acceptance.' };
  writeFileSync(folder + '/result.json', JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
} catch (error) {
  if (page) {
    try { await page.screenshot({ path: folder + '/failed-state.png', fullPage: true }); } catch { /* The browser may have terminated; retain the original failure. */ }
  }
  writeFileSync(folder + '/result.json', JSON.stringify({ passed, failed: 1, error: String(error) }, null, 2));
  throw error;
} finally { await browser?.close(); await worker?.stop(); }
