// D02/D03 bounded journey. Local synthetic Worker/D1 only; no live host or provider.
// BR-UX-01 BR-UX-02 BR-UX-06 BR-UX-07 BR-ID-02 BR-DATA-02
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { startWorker, identity, client } from '../lib/worker.mjs';
const { chromium } = await import(process.env.SAHA_BROWSER_PACKAGE ?? '@playwright/test');
const evidence = 'tests/reports/worker-today-save';
mkdirSync(evidence, { recursive: true });
let worker, browser, passed = 0;
const check = (value, message) => { assert.ok(value, message); passed++; };
try {
  worker = await startWorker({ port: process.env.SAHA_TODAY_PORT ?? '9157', name: 'saha-worker-today' });
  const api = client(worker.base), run = crypto.randomUUID().slice(0, 8);
  const owner = identity('owner', run, 'Synthetic Owner'), asha = identity('asha', run, 'Synthetic ASHA');
  const wo = await api.get(owner, '/api/workspace'), wa = await api.get(asha, '/api/workspace');
  assert.equal(wo.status, 200); assert.equal(wa.status, 200);
  const org = wo.json.organisation.id, person = wo.json.people.find(p => p.name === 'Meena Devi');
  assert.ok(person);
  const invite = await api.command(owner, { type: 'createInvite', accountCode: wa.json.user.accountCode, label: 'Synthetic ASHA', role: 'asha', teamIds: ['default'] }, org);
  assert.equal(invite.status, 200);
  assert.equal((await api.command(asha, { type: 'joinOrganisation', token: invite.json.result.token })).status, 200);
  assert.equal((await api.command(owner, { type: 'assignPatient', personId: person.id, version: person.version, teamId: 'default', assignedTo: wa.json.user.userId, reason: 'Synthetic Today journey' }, org)).status, 200);
  const before = (await api.get(asha, '/api/workspace', org)).json;
  browser = await chromium.launch({ headless: true, ...(process.env.SAHA_CHROMIUM ? { executablePath: process.env.SAHA_CHROMIUM } : {}) });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, extraHTTPHeaders: asha.headers });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  page.setDefaultTimeout(25000);
  await page.goto(worker.base + '/worker-today/');
  await page.getByText('Work list loaded.', { exact: false }).waitFor();
  check(await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button').count() === 3, 'Three stable entry destinations');
  check(await page.locator('article.next h2').innerText() === 'Meena Devi', 'Real scoped source feeds the next record');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Phone entry has no horizontal overflow');
  const entry = await api.get(asha, '/api/workspace', org);
  check(entry.json.visits.length === before.visits.length, 'Loading the entry creates no visit');
  await page.screenshot({ path: evidence + '/today.png', fullPage: true });
  await page.locator('article.next .action').click();
  await page.getByRole('heading', { name: 'Meena Devi', exact: true }).waitFor();
  check(new URL(page.url()).pathname === '/app', 'Existing protected app owns the encounter');
  await page.getByRole('button', { name: 'Start visit', exact: true }).click();
  await page.getByRole('combobox', { name: 'Go to observation or save', exact: true }).selectOption('fact:weight');
  await page.getByRole('textbox', { name: 'Weight · kg', exact: true }).fill('57.5');
  const nav = page.getByRole('navigation', { name: 'App navigation' });
  await nav.getByRole('button', { name: 'Home', exact: true }).click();
  await page.getByRole('alertdialog').waitFor();
  await page.getByRole('button', { name: 'Keep editing', exact: true }).click();
  check(await page.getByRole('textbox', { name: 'Weight · kg', exact: true }).inputValue() === '57.5', 'Existing interruption guard retains unsaved input');
  await page.getByRole('combobox', { name: 'Go to observation or save', exact: true }).selectOption('facts-save');
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await page.getByText('Draft saved in the workspace.', { exact: true }).waitFor();
  const saved = (await api.get(asha, '/api/workspace', org)).json;
  const draft = saved.visits.find(v => v.personId === person.id);
  check(draft?.state === 'draft', 'Saved record is an unconfirmed draft, not programme acceptance');
  check(draft?.facts.weight === '57.5', 'Actual backend read-back retains entered value');
  check(saved.visits.length === before.visits.length + 1, 'One explicit start produces one visit');
  await page.getByRole('tab', { name: /Review & act/ }).click();
  check(await page.getByRole('button', { name: 'Confirm visit', exact: true }).isDisabled(), 'Existing person-context check remains; no new approval');
  await page.screenshot({ path: evidence + '/saved-draft-review.png', fullPage: true });
  await page.goto(worker.base + '/worker-today/');
  await page.getByText('Work list loaded.', { exact: false }).waitFor();
  await page.locator('article.next .action').click();
  await page.getByRole('heading', { name: 'Meena Devi', exact: true }).waitFor();
  const reopened = (await api.get(asha, '/api/workspace', org)).json;
  check(reopened.visits.length === saved.visits.length, 'Reopening from Today creates no duplicate');
  check(reopened.visits.find(v => v.id === draft.id)?.facts.weight === '57.5', 'Saved draft survives the new-entry round trip');
  check(errors.length === 0, 'No browser application exceptions');
  const report = { passed, failed: 0, scope: 'Real Chromium/local synthetic Worker and D1. Existing editor reused; no offline, physical-device, clinical, government or production acceptance.' };
  writeFileSync(evidence + '/result.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} catch (error) {
  writeFileSync(evidence + '/result.json', JSON.stringify({ passed, failed: 1, error: String(error), workerTail: worker?.output().slice(-3000) }, null, 2));
  throw error;
} finally { await browser?.close(); await worker?.stop(); }
