import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
let passed=0;
const pin=readFileSync('lib/saha/ai-version-pin.ts','utf8');
const agent=readFileSync('lib/saha/agent.ts','utf8');
const provider=readFileSync('lib/saha/agent-provider.ts','utf8');
const history=readFileSync('lib/saha/capability-lifecycle.ts','utf8');
const panel=readFileSync('app/provider-history-panel.tsx','utf8');
const check=(value,message)=>{assert.ok(value,message);passed++;};
for(const token of ['capability','provider','modelRelease','agentRelease','prompt','tool','data','evaluation'])check(pin.includes(token),`version pin retains ${token}`);
check(pin.includes("evaluation.manifestHash !== pin.capability.manifestHash"),'evaluation must match capability manifest');
check(pin.includes("evaluation.state !== 'completed'")&&pin.includes('evaluation.metrics?.passed'),'only a completed passing evaluation can be pinned');
check(agent.includes('versionPin:pin')&&agent.includes('versionPin:pin,agent:AGENT_VERSION'),'prepared request and input hash bind the exact version pin');
check(agent.includes('sameVersionPin(r.versionPin,livePin)'),'current authority recomputes and compares every version dimension');
check(agent.includes('Provider, model, prompt, tool, data or evaluation version changed'),'stale version refusal is explicit');
check(provider.includes('assertCompleteVersionPin(r.versionPin)'),'invocation refuses missing or malformed version evidence');
check(provider.includes('versionPin:r.versionPin'),'HTTP provider receives exact version evidence');
check(!provider.includes('versionPin:r.versionPin??'),'no missing-version fallback exists');
check(history.includes('capabilityManifestHash')&&history.includes('corpusHash'),'history exposes capability and evaluation identities');
check(panel.includes('Prompt / tool / data')&&panel.includes('Evaluation'),'governance UI exposes every version dimension');
console.log(JSON.stringify({passed,failed:0}));
