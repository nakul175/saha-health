// Stored as operations.memberLanguages[userId]. It follows the member in this organisation only, is versioned like the
// display name (slice 9b) and changes nothing about identity, role, teams or access.
export type LanguageRecord = { language: Language; version: number; at: string };
export const MEMBER_LANGUAGE_LIMIT = 2000;
export function languageOf(records: Record<string, LanguageRecord> | undefined, userId: string): { language: Language; version: number } {
  const own = records && Object.prototype.hasOwnProperty.call(records, userId) ? records[userId] : undefined;
  return own && LANGUAGES.includes(own.language) ? { language: own.language, version: own.version } : { language: DEFAULT_LANGUAGE, version: 0 };
}
export type LanguageChange = { ok: true; record: LanguageRecord; prior: Language } | { ok: false; status: 409 | 422; message: string };
export function chooseLanguage(records: Record<string, LanguageRecord>, userId: string, language: Language, version: number, now: string): LanguageChange {
  const current = languageOf(records, userId);
  if (version !== current.version) return { ok: false, status: 409, message: 'Your language in this organisation changed. Refresh and try again.' };
  if (language === current.language) return { ok: false, status: 422, message: 'This is already your language in this organisation.' };
  if (!Object.prototype.hasOwnProperty.call(records, userId) && Object.keys(records).length >= MEMBER_LANGUAGE_LIMIT) return { ok: false, status: 422, message: 'Language choice limit reached for this organisation.' };
  return { ok: true, record: { language, version: current.version + 1, at: now }, prior: current.language };
}
