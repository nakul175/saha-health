def emit(path, value):
    OUTPUTS[path] = value.encode() if isinstance(value, str) else value


def csv_text(rows):
    stream = io.StringIO(newline='')
    writer = csv.writer(stream, lineterminator='\n')
    writer.writerows(rows)
    return stream.getvalue()


def md(value):
    return str(value).replace('|', '\\|').replace('\n', ' ')


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def relative(path):
    return path.relative_to(ROOT).as_posix()


def transcribe_docx(path):
    ns = {'w': 'http://schemas.openxmlformats.org/wordprocessingml/2006/main'}
    with ZipFile(path) as archive:
        body = ET.fromstring(archive.read('word/document.xml')).find('w:body', ns)
    def text(node):
        return ''.join(t.text or '' for t in node.findall('.//w:t', ns))
    lines = [f'# Original target design — {path.stem}', '',
             'Unchanged design content transcribed from the archived v1.0 Word file. '
             'This is a target specification, not an R11 implementation claim. '
             'See the [current index](../current/DOCUMENTATION-INDEX.md).', '',
             f'[Original editable file](../history/v1.0/{path.name})', '']
    for item in body:
        if item.tag.endswith('}p'):
            value = text(item)
            if not value:
                continue
            style = item.find('w:pPr/w:pStyle', ns)
            style_name = style.get('{'+ns['w']+'}val', '') if style is not None else ''
            heading = re.fullmatch(r'Heading([1-6])', style_name, re.I)
            lines += [('#' * min(int(heading[1]) + 1, 6) + ' ' if heading else '') + value, '']
        elif item.tag.endswith('}tbl'):
            rows = [[text(c) for c in row.findall('w:tc', ns)] for row in item.findall('w:tr', ns)]
            if not rows:
                continue
            width = max(map(len, rows))
            rows = [row + [''] * (width-len(row)) for row in rows]
            lines += ['| '+' | '.join(md(c) for c in rows[0])+' |', '| '+' | '.join(['---']*width)+' |']
            lines += ['| '+' | '.join(md(c) for c in row)+' |' for row in rows[1:]]
            lines += ['']
    return '\n'.join(lines).rstrip()+'\n'


