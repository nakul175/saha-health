# cached results. No workbook editing/recalculation or formula evaluation occurs.
ns = {'s': 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}
workbook_rows = []
with ZipFile(HISTORY/'Health-AI-Delivery-Control-Workbook-v1.0.xlsx') as archive:
    strings = []
    if 'xl/sharedStrings.xml' in archive.namelist():
        strings = [''.join(t.text or '' for t in si.findall('.//s:t', ns))
                   for si in ET.fromstring(archive.read('xl/sharedStrings.xml')).findall('s:si', ns)]
    rels = {r.attrib['Id']: r.attrib['Target'] for r in ET.fromstring(archive.read('xl/_rels/workbook.xml.rels'))}
    workbook = ET.fromstring(archive.read('xl/workbook.xml'))
    for sheet in workbook.findall('s:sheets/s:sheet', ns):
        rid = sheet.attrib['{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id']
        target = rels[rid]
        target = target.lstrip('/') if target.startswith('/') else 'xl/'+target
        cells, formulas = {}, []
        for cell in ET.fromstring(archive.read(target)).findall('.//s:sheetData/s:row/s:c', ns):
            ref = cell.attrib['r']; letters, number = re.fullmatch(r'([A-Z]+)(\d+)', ref).groups()
            col = 0
            for letter in letters:
                col = col*26 + ord(letter)-64
            value = cell.find('s:v', ns); value = value.text if value is not None and value.text is not None else ''
            kind = cell.attrib.get('t')
            if kind == 's':
                value = strings[int(value)] if value else ''
            elif kind == 'inlineStr':
                value = ''.join(t.text or '' for t in cell.findall('.//s:t', ns))
            formula = cell.find('s:f', ns)
            if formula is not None:
                formulas.append({'cell':ref,'formula':formula.text or '', 'cached':value,'attributes':formula.attrib})
                value = '='+ (formula.text or '')
            cells[(int(number), col)] = value
        height = max(r for r,c in cells); width = max(c for r,c in cells)
        filename = re.sub(r'[^A-Za-z0-9]+','-',sheet.attrib['name']).strip('-')+'.csv'
        emit('docs/reference/workbook/'+filename, csv_text([[cells.get((r,c),'') for c in range(1,width+1)] for r in range(1,height+1)]))
        workbook_rows.append({'sheet':sheet.attrib['name'],'file':filename,'rows':height,'columns':width,'formulas':formulas})
emit('docs/reference/workbook/manifest.json', json.dumps(workbook_rows,indent=2)+'\n')

